export function getSupportedLanguage(language) {
  return Object.hasOwn(SITE_COPY, language) ? language : DEFAULT_LANGUAGE
}

export function getHabitatLabel(habitatId, language = DEFAULT_LANGUAGE) {
  const labels = HABITAT_LABELS[habitatId]

  if (!labels) {
    return habitatId
  }

  const resolvedLanguage = getSupportedLanguage(language)
  return labels[resolvedLanguage] ?? labels[DEFAULT_LANGUAGE]
}

export function getHabitatOptions(language = DEFAULT_LANGUAGE) {
  return Object.keys(HABITAT_LABELS).map((id) => ({
    id,
    label: getHabitatLabel(id, language),
  }))
}

